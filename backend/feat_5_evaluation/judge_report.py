"""Rebuild the mandatory-category evidence and specification gap inventory.

Runs static analysis only. No fixture code is executed, trained on, or copied
into the report. This is a development report, never an official judge score.
"""
import json
from pathlib import Path
import re
import sys
from datetime import datetime, timezone

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'backend'))
from feat_1_scan.analyzer import analyze, REASONS, PREFIX
from feat_1_scan.dependency_instructions import REASONS as HELPER_RULES
from feat_5_evaluation.evaluate import run_evaluation, metrics
from feat_6_runtime.test_rules import FIXTURES
from feat_6_runtime.versions import ENGINE_VERSION, POLICY_VERSION


def build():
    specification = (ROOT / 'more_info.md').read_text().split('## 4. Beyond')[0]
    rule_ids = re.findall(r'^\| ((?:SEC|EXF|DES|PER|OBF|DEP|RES|NET|AIT)-\d{3}) \|', specification, re.M)
    rows = []
    for rule in rule_ids:
        positive = benign = None
        if rule in FIXTURES:
            positive_result = analyze(FIXTURES[rule][0])
            benign_result = analyze(FIXTURES[rule][1])
            positive = positive_result['analysis_complete'] and any(f['rule_id'] == 'CG-' + rule for f in positive_result['findings'])
            benign = benign_result['analysis_complete'] and benign_result['verdict'] == 'allow'
        status = ('partial_live' if rule in REASONS else 'helper_only_not_live'
                  if rule in HELPER_RULES else 'not_implemented')
        rows.append({'rule_id': rule, 'category': PREFIX[rule.split('-')[0]],
                     'status': status, 'positive_pass': positive, 'benign_pass': benign})
    categories = []
    for category in sorted({row['category'] for row in rows}):
        subset = [row for row in rows if row['category'] == category]
        categories.append({'category': category, 'specified_rules': len(subset),
            'live_rules': sum(row['status'] == 'partial_live' for row in subset),
            'positive_and_benign_pass': sum(row['positive_pass'] is True and row['benign_pass'] is True for row in subset),
            'missing_rules': [row['rule_id'] for row in subset if row['status'] != 'partial_live']})
    evaluation = run_evaluation()
    sweep = []
    for threshold in (.25, .35, .45, .5, .6, .7, .8, .9, .95):
        tp = fp = tn = fn = 0
        for row in evaluation['results']:
            trace = row['score_trace']
            blocked = (not row['analysis_complete'] or trace['critical_override']
                       or trace['final_score'] >= threshold)
            unsafe = row['expected'] == 'block'
            tp += unsafe and blocked
            fp += not unsafe and blocked
            tn += not unsafe and not blocked
            fn += unsafe and not blocked
        sweep.append({'threshold': threshold, **metrics(tp, fp, tn, fn)})
    return {'generated_at': datetime.now(timezone.utc).isoformat(),
        'engine_version': ENGINE_VERSION, 'policy_version': POLICY_VERSION,
        'categories': categories, 'rules': rows,
        'all_nine_have_verified_live_rules': all(c['positive_and_benign_pass'] > 0 for c in categories),
        'all_specification_rows_complete': False,
        'coverage_caveat': 'A positive/benign pair proves one supported pattern, not the full rule specification. All live entries remain partial until every specified trigger and guard is verified.',
        'development_evaluation': evaluation, 'development_threshold_sweep': sweep,
        'threshold_decision': 'Retain PRD default 0.50. This sweep is diagnostic; no held-out threshold selection or sealed evaluation has occurred.',
        'official_judging': 'Private hidden-set formula is unknown. This report computes development metrics only.'}


if __name__ == '__main__':
    report = build()
    target = ROOT / 'docs/reports/judge-readiness.json'
    target.write_text(json.dumps(report, indent=2) + '\n')
    lines = ['# Nine-category coverage', '', report['coverage_caveat'], '',
             '| Required category | Spec rows | Live partial rules | Passing fixture pairs | Remaining rule IDs |',
             '|---|---:|---:|---:|---|']
    for row in report['categories']:
        lines.append(f"| {row['category']} | {row['specified_rules']} | {row['live_rules']} | {row['positive_and_benign_pass']} | {', '.join(row['missing_rules'])} |")
    lines += ['', 'Generated by `backend/feat_5_evaluation/judge_report.py`.',
              'Machine-readable rule statuses, public metrics and threshold sweep: [judge-readiness.json](reports/judge-readiness.json).',
              '', 'Helper-only rules are not counted as live detection coverage. OBF-004 is a supporting alias-resolution capability, not a standalone vulnerability finding.']
    (ROOT / 'docs/nine-category-coverage.md').write_text('\n'.join(lines) + '\n')
    print(json.dumps({'report': str(target), 'all_nine_verified': report['all_nine_have_verified_live_rules'],
                      'binary': report['development_evaluation']['binary'],
                      'categories': report['categories']}, indent=2))
